var e=`[Copy-on-Write](#/posts/cow-fork) 를 넣고 나서, 스왑 테스트를 돌리다 이 그림에 도착했습니다. 부모와 자식이 공유하던 페이지가 메모리 부족으로 스왑에 내려가면, 두 프로세스가 같은 스왑 슬롯을 가리키게 됩니다.

\`\`\`
부모 ──┐
       ├──> [스왑 슬롯 7]
자식 ──┘

자식이 먼저 swap-in → 슬롯 7 을 비트맵에서 해제(반납)
부모가 나중에 swap-in → 슬롯 7 은 이미 다른 데이터의 자리
                        부모의 페이지는 조용히 오염
\`\`\`

무서운 점은 크래시가 안 난다는 것입니다. 부모가 그 페이지를 읽는 먼 훗날, 틀린 값이 나올 뿐입니다. 이런 버그는 터진 자리와 원인의 자리가 멀어서, 구조로 막지 않으면 못 잡는다고 판단했습니다.

## 첫 구현은 문제를 피해서 갔다

처음에는 문제 자체를 없애는 쪽을 택했습니다. fork 중에 스왑된 페이지를 만나면 그 자리에서 디스크를 읽어 자식 프레임을 즉시 만들어 버리는 겁니다. 공유가 안 생기니 반납 문제도 없습니다. 당시 트러블슈팅 노트를 그대로 옮깁니다.

\`\`\`
초기 구현의 문제

부모 page
  swapped=true
  swap_idx=5

fork 중
  disk_read(slot 5)
  자식 frame 즉시 생성

결과
  swap 된 page 는 COW 의 lazy 전략에서 벗어남
\`\`\`

돌아가긴 했는데, 적어 놓고 보니 모순이 보였습니다. 메모리에 있는 페이지는 게으르게 미루면서, 스왑에 있는 페이지만 성급하게 복사하고 있었습니다. 회피가 아니라 정면으로 풀기로 하고, 스왑 슬롯 자체를 공유 대상으로 바꿨습니다. fork 는 슬롯 번호와 상태만 복사하고, 실제 디스크 읽기는 접근한 프로세스가 접근한 순간에 합니다.

## 프레임에 했던 일을 슬롯에도 한다

공유 프레임을 \`ref_count\` 로 관리했던 것과 같은 논리를 슬롯에 적용했습니다. 슬롯별 참조 수 배열을 두고, 마지막 참조가 풀리는 순간에만 비트맵을 해제합니다. 먼저 swap-in 한 쪽은 계수만 내리고 슬롯은 남겨 둡니다.

\`\`\`c
/* vm/anon.c — 슬롯 수명은 이 세 함수만 만진다 */
static size_t swap_slot_alloc (void);   /* 비트맵 확보 + ref_count = 1 */
static void   swap_slot_ref   (size_t slot);   /* 공유 시작, 계수 증가 */
static void   swap_slot_unref (size_t slot);   /* 0 이 되는 순간에만 반납 */

static struct bitmap *disk_bitmap;
static size_t *swap_ref_count;   /* 슬롯별 참조 수 */
static struct lock swap_lock;    /* 계수와 비트맵을 한 락으로 */
\`\`\`

수명 연산을 세 함수로 좁힌 것은 의도한 결정입니다. 반납 조건이 코드 곳곳에 흩어지면, 이 버그는 반드시 다른 얼굴로 돌아옵니다.

## 숫자만으로는 회수를 못 한다

여기까지 만들고 나니 더 근본적인 질문이 남았습니다. 참조 계수는 "몇 개가 보는가" 를 답합니다. 그런데 공유 프레임을 회수하려면 "누가 보는가" 를 알아야 합니다. 그 프레임을 가리키던 페이지 테이블 항목을 전부 지워야 하는데, 숫자는 지울 자리를 알려 주지 않기 때문입니다.

그래서 수명 판단은 ref_count 가, 회수 대상 식별은 \`(page, thread)\` 소유자 목록이 맡도록 책임을 나누는 설계를 잡았습니다. 이 소유자 목록 보완은 커밋된 코드가 아니라 설계 단계입니다. 저장소에도 완료 기능으로 적지 않았고, 여기에도 같은 경계를 둡니다. 완성한 것과 설계한 것을 섞으면 그때부터 문서를 믿을 수 없게 됩니다.

슬롯 참조 계수의 전체 구현은 [\`vm/anon.c\` (woonyong 브랜치)](https://github.com/woonyong-kr/pintos/blob/woonyong/pintos/vm/anon.c) 에 있습니다. 저장소의 main 에는 팀 통합 결과가 올라가 있어서, 이 글이 다루는 구현은 제 작업 브랜치에서 봅니다.`;export{e as default};